import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const galleryDirectory = path.join(process.cwd(), "public", "gallery");
const outputFile = path.join(process.cwd(), "app", "gallery.generated.ts");
const supportedImage = /^\d+\.(?:avif|jpe?g|png|webp)$/i;

const files = (await readdir(galleryDirectory))
  .filter((file) => supportedImage.test(file))
  .sort((left, right) => left.localeCompare(right, "en", { numeric: true }));

if (files.length < 3) {
  throw new Error("The daily gallery needs at least three numbered images.");
}

const source = `// This file is generated by scripts/generate-gallery-manifest.mjs.\nexport const galleryImages = ${JSON.stringify(
  files.map((file) => `/gallery/${file}`),
  null,
  2,
)} as const;\n`;

await writeFile(outputFile, source, "utf8");
console.log(`Gallery manifest: ${files.length} images`);
